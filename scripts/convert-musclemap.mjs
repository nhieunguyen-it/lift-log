// Converts MuscleMap (MIT, (c) 2026 Melih Colpan) male SVG paths into src/components/analyze/bodyMapPaths.ts.
// Usage: node scripts/convert-musclemap.mjs [dir-with-downloaded-swift-files]
// Download first (dev-time only):
//   https://raw.githubusercontent.com/melihcolpan/MuscleMap/main/Sources/MuscleMap/Data/MaleFrontPaths.swift
//   https://raw.githubusercontent.com/melihcolpan/MuscleMap/main/Sources/MuscleMap/Data/MaleBackPaths.swift
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] ?? '/tmp/musclemap';
const out = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/components/analyze/bodyMapPaths.ts',
);

// viewBox from BodyPathData.swift (BodyViewBox.maleFront / maleBack).
const VIEW_BOXES = { front: '0 95 727 1280', back: '718 95 727 1280' };

/** slug -> MuscleId (draw order = order listed). Anything not listed is skipped. `part` picks a single path entry. */
const MAP = {
  front: [
    ['trapezius', 'upper_back'],
    ['deltoids', 'side_delts'],
    ['frontDeltoid', 'front_delts'],
    ['chest', 'chest'],
    ['abs', 'abs'],
    ['obliques', 'obliques'],
    ['biceps', 'biceps'],
    ['triceps', 'triceps'],
    ['forearm', 'forearms'],
    ['quadriceps', 'quads'],
    ['adductors', 'adductors'],
    ['calves', 'calves'],
  ],
  back: [
    ['trapezius', 'upper_back'],
    ['rotatorCuff', 'upper_back'],
    // MuscleMap has no lat slug: its "upperBack" artwork entry 0 is the large lat shape, entry 1 the teres/upper strip.
    ['upperBack', 'lats', 0],
    ['upperBack', 'upper_back', 1],
    ['deltoids', 'rear_delts'],
    ['rearDeltoid', 'rear_delts'],
    ['triceps', 'triceps'],
    ['lowerBack', 'lower_back'],
    ['forearm', 'forearms'],
    ['gluteal', 'glutes'],
    ['hamstring', 'hamstrings'],
    ['adductors', 'adductors'],
    ['calves', 'calves'],
  ],
};
// Neutral silhouette parts (not trainable).
const NEUTRAL = {
  front: [
    'head',
    'hair',
    'neck',
    'hands',
    'knees',
    'tibialis',
    'ankles',
    'feet',
    'serratus',
    'hipFlexors',
  ],
  back: ['head', 'hair', 'neck', 'hands', 'ankles', 'feet'],
};

function parse(file) {
  const s = readFileSync(join(src, file), 'utf8');
  const res = {};
  for (const b of s.split('BodyPartPathData(').slice(1)) {
    const slug = b.match(/slug: \.(\w+)/)[1];
    res[slug] = [...b.matchAll(/"(M[^"]+)"/g)].map((m) => m[1]);
  }
  return res;
}

const regions = [];
const silhouette = [];
for (const view of ['front', 'back']) {
  const parts = parse(view === 'front' ? 'MaleFrontPaths.swift' : 'MaleBackPaths.swift');
  const merged = new Map();
  for (const [slug, id, entry] of MAP[view]) {
    if (!parts[slug]) throw new Error(`missing slug ${slug}`);
    // Left/right arrays interleave; for split slugs take the entry index from each side (2 sides).
    let ds = parts[slug];
    if (entry !== undefined)
      ds = ds.filter((_, i) => i % 2 === entry || (ds.length === 4 ? i % 2 === entry : false));
    merged.set(id, [...(merged.get(id) ?? []), ...ds]);
  }
  for (const [id, ds] of merged) regions.push({ muscleId: id, view, d: ds.join('') });
  silhouette.push({ view, d: NEUTRAL[view].flatMap((s) => parts[s] ?? []).join('') });
}

const ts = `// GENERATED by scripts/convert-musclemap.mjs - do not edit.
// Anatomy paths: MuscleMap by Melih Colpan, MIT licence (see THIRD_PARTY_NOTICES.md).
import type { MuscleId } from '@/data';

export type BodyView = 'front' | 'back';

export interface BodyRegion {
  muscleId: MuscleId;
  view: BodyView;
  d: string;
}

/** Per-view viewBox (front and back live side by side in MuscleMap's source artwork). */
export const VIEW_BOXES: Record<BodyView, string> = ${JSON.stringify(VIEW_BOXES)};

/** Tappable muscle regions, in draw order (later regions paint over earlier ones). */
export const BODY_REGIONS: BodyRegion[] = ${JSON.stringify(regions)};

/** Non-interactive neutral parts (head, hands, feet, knees, neck, tibialis ...). */
export const SILHOUETTE: Record<BodyView, string> = ${JSON.stringify(Object.fromEntries(silhouette.map((x) => [x.view, x.d])))};
`;
writeFileSync(out, ts);
console.log(regions.map((r) => `${r.view}:${r.muscleId}:${r.d.length}`).join('\n'));
